const capFirst = (s: string) => (s ? s[0]!.toUpperCase() + s.slice(1) : s);
const viArg = (label: string) => ARG_LABELS_VI[label] ?? label;

/**
 * Localizes validation messages (`validateProgram`) and `InvalidOperation`
 * messages coming from `@robolab/blocks` (which stays English for the server).
 */
export function localizeBlockIssue(message: string, locale: Locale = getLocale()): string {
  if (locale === 'en') return message;
  const exact = ISSUE_EXACT_VI[message];
  if (exact) return exact;

  const typeNum = /^Type a number for (.+)\.$/.exec(message);
  if (typeNum) return `Nhập một số cho ${viArg(typeNum[1]!)}.`;

  const between = /^The (.+) should be between (-?\d+(?:\.\d+)?) and (-?\d+(?:\.\d+)?)( .+)?\.$/.exec(message);
  if (between) return `${capFirst(viArg(between[1]!))} nên nằm từ ${between[2]} đến ${between[3]}${between[4] ?? ''}.`;

  const atLeast = /^The (.+) should be at least (-?\d+(?:\.\d+)?)( .+)?\.$/.exec(message);
  if (atLeast) return `${capFirst(viArg(atLeast[1]!))} phải ít nhất là ${atLeast[2]}${atLeast[3] ?? ''}.`;

  const atMost = /^The (.+) should be at most (-?\d+(?:\.\d+)?)( .+)?\.$/.exec(message);
  if (atMost) return `${capFirst(viArg(atMost[1]!))} nhiều nhất là ${atMost[2]}${atMost[3] ?? ''}.`;

  const whole = /^Use a whole number for (.+)\.$/.exec(message);
  if (whole) return `Dùng số nguyên cho ${viArg(whole[1]!)}.`;

  const dupFn = /^There are two functions called “(.+)”\.$/.exec(message);
  if (dupFn) return `Có hai hàm cùng tên “${dupFn[1]}”.`;

  return message;
}
